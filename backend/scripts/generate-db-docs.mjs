// Generates docs/DATABASE_DICTIONARY.md from the migrations, applied to an in-memory PostgreSQL.
// Run: npm run docs:db   (no network, no real database)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { pg_trgm } from "@electric-sql/pglite/contrib/pg_trgm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "prisma", "migrations");
const outFile = join(root, "..", "docs", "DATABASE_DICTIONARY.md");

const domains = {
  "Identity & access": [
    "users",
    "roles",
    "permissions",
    "role_permissions",
    "user_roles",
    "sessions",
    "one_time_tokens",
    "mfa_credentials",
    "addresses",
    "consents",
    "security_events",
  ],
  Catalogue: [
    "categories",
    "products",
    "product_variants",
    "media_assets",
    "product_images",
    "product_categories",
    "collections",
    "collection_products",
    "tax_rates",
  ],
  Inventory: ["inventory", "inventory_reservations", "inventory_movements"],
  "Cart & wishlist": ["carts", "cart_items", "wishlists", "wishlist_items"],
  "Orders & payments": [
    "orders",
    "order_items",
    "order_status_history",
    "payments",
    "payment_webhook_events",
    "refunds",
    "coupons",
    "coupon_redemptions",
  ],
  "Shipping & returns": [
    "shipping_rates",
    "shipments",
    "shipment_events",
    "return_requests",
    "return_items",
  ],
  "Content, reviews & settings": ["reviews", "cms_pages", "banners", "site_settings"],
  "Audit & operations": ["admin_audit_logs", "idempotency_keys", "notification_logs"],
  "AI assistant": ["ai_conversations", "ai_messages"],
};

const db = new PGlite({ extensions: { pg_trgm } });
for (const name of readdirSync(migrationsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()) {
  await db.exec(readFileSync(join(migrationsDir, name, "migration.sql"), "utf8"));
}

const rows = async (sql, params) => (await db.query(sql, params)).rows;
const tables = (
  await rows(
    `SELECT table_name FROM information_schema.tables WHERE table_schema='public' ORDER BY 1`,
  )
).map((r) => r.table_name);

const grouped = new Set(Object.values(domains).flat());
const missing = tables.filter((t) => !grouped.has(t));
const unknown = [...grouped].filter((t) => !tables.includes(t));
if (missing.length || unknown.length) {
  throw new Error(
    `Domain map out of date. Missing: ${missing.join(", ") || "-"}; unknown: ${unknown.join(", ") || "-"}`,
  );
}

const esc = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
const out = [];
out.push("# Database dictionary", "");
out.push(
  "> Generated by `npm run docs:db` (in `backend/`) from `backend/prisma/migrations`. Do not edit by hand.",
  "",
);
out.push(
  `${tables.length} tables in the \`public\` schema of the LLI database. Money is integer paise; timestamps are \`timestamptz\`; primary keys are UUIDs from \`gen_random_uuid()\`.`,
  "",
);

for (const [domain, list] of Object.entries(domains)) {
  out.push(`## ${domain}`, "");
  for (const table of list) {
    out.push(`### \`${table}\``, "");
    const cols = await rows(
      `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS notnull,
              pg_get_expr(d.adbin, d.adrelid) AS dflt, a.attgenerated <> '' AS generated
         FROM pg_attribute a
         LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = $1::regclass AND a.attnum > 0 AND NOT a.attisdropped
        ORDER BY a.attnum`,
      [`public.${table}`],
    );
    out.push("| Column | Type | Null | Default |", "|---|---|---|---|");
    for (const c of cols) {
      const dflt = c.generated ? "generated" : (c.dflt ?? "");
      out.push(
        `| \`${c.name}\` | ${esc(c.type)} | ${c.notnull ? "no" : "yes"} | ${dflt ? "`" + esc(dflt) + "`" : ""} |`,
      );
    }
    out.push("");

    const cons = await rows(
      `SELECT conname AS name, contype AS type, pg_get_constraintdef(oid) AS def
         FROM pg_constraint WHERE conrelid = $1::regclass ORDER BY contype, conname`,
      [`public.${table}`],
    );
    const label = { p: "Primary key", u: "Unique", f: "Foreign key", c: "Check" };
    if (cons.length) {
      out.push("**Constraints**", "");
      for (const c of cons)
        out.push(`- ${label[c.type] ?? c.type}: \`${c.name}\` — \`${esc(c.def)}\``);
      out.push("");
    }
    const idx = await rows(
      `SELECT indexname AS name, indexdef AS def FROM pg_indexes
        WHERE schemaname='public' AND tablename=$1
          AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE conrelid = $2::regclass)
        ORDER BY indexname`,
      [table, `public.${table}`],
    );
    if (idx.length) {
      out.push("**Indexes**", "");
      for (const i of idx)
        out.push(
          `- \`${i.name}\` — \`${esc(i.def.replace(/^CREATE (UNIQUE )?INDEX \S+ ON public\./, (m, u) => (u ? "UNIQUE " : "")))}\``,
        );
      out.push("");
    }
    const trg = await rows(
      `SELECT tgname AS name, pg_get_triggerdef(oid) AS def FROM pg_trigger
        WHERE tgrelid = $1::regclass AND NOT tgisinternal ORDER BY tgname`,
      [`public.${table}`],
    );
    if (trg.length) {
      out.push("**Triggers**", "");
      for (const t of trg) out.push(`- \`${t.name}\``);
      out.push("");
    }
  }
}

const enums = await rows(
  `SELECT t.typname AS name, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder) AS vals
     FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid GROUP BY t.typname ORDER BY 1`,
);
out.push("## Enumerations", "");
for (const e of enums) out.push(`- \`${e.name}\`: ${e.vals}`);
out.push("");

writeFileSync(outFile, out.join("\n"), "utf8");
await db.close();
console.log(`Wrote ${outFile} (${tables.length} tables, ${enums.length} enums)`);
