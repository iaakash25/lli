// Generates backend/db/seed/dev_catalogue.sql from the storefront's current hard-coded catalogue
// (src/lib/catalog.ts). Development data only: placeholder stock, placeholder media keys, no costs.
// Run: npm run seed:dev:generate   (no network, no database)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { assetsDir, loadCatalog } from "./lib/load-catalog.mjs";

const outFile = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "db",
  "seed",
  "dev_catalogue.sql",
);

// Opening stock per variant for the storefront's three stock labels (low_stock_threshold defaults to 3).
const STOCK_QTY = { in: 25, low: 2, out: 0 };

export async function buildDevCatalogueSql() {
  const { PRODUCTS, COLLECTIONS, COLOURS, assetFiles } = await loadCatalog();

  const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);
  const b = (v) => (v ? "true" : "false");
  const slugify = (s) =>
    s
      .toLowerCase()
      .replace(/&/g, " ")
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");
  const rows = (list) => list.map((r) => `    (${r.join(", ")})`).join(",\n");

  // ── Categories: two parents, one child per product type ────────────────────────────────
  const collectionBySlug = Object.fromEntries(COLLECTIONS.map((c) => [c.slug, c]));
  const parents = [
    { slug: "bags", name: "Bags", collection: collectionBySlug["bags"] },
    {
      slug: "small-leather-goods",
      name: "Small Leather Goods",
      collection: collectionBySlug["small-leather-goods"],
    },
  ];
  const types = [...new Set(PRODUCTS.map((p) => p.type))];
  const childRows = types.map((type, i) => {
    const sample = PRODUCTS.find((p) => p.type === type);
    const parent = parents.find((par) => par.collection.filter(sample));
    if (!parent) throw new Error(`Product type ${type} belongs to no parent category`);
    return [q(slugify(type)), q(type), q(parent.slug), String(i + 1)];
  });

  // ── Media: one row per distinct image used by products or collection heroes ──────────────
  const usedImages = [
    ...new Set([...PRODUCTS.flatMap((p) => p.images), ...COLLECTIONS.map((c) => c.image)]),
  ];
  const mediaRows = usedImages.map((name) => {
    const file = assetFiles.get(name);
    const bytes = readFileSync(join(assetsDir, file));
    const sha = createHash("sha256").update(bytes).digest("hex");
    return [
      q(`dev/catalogue/${file}`),
      q("image/jpeg"),
      String(bytes.length),
      q(sha),
      q(`Placeholder image: ${name}`),
    ];
  });
  const key = (name) => `dev/catalogue/${assetFiles.get(name)}`;

  // ── Products, variants, stock ───────────────────────────────────────────────────────────
  const productRows = PRODUCTS.map((p) => [
    q(p.slug),
    q(p.name),
    q(p.tagline),
    q(p.type),
    q(p.gender.toUpperCase()),
    q(p.material),
    q(p.dimensions),
    b(p.isNew),
    b(p.bestseller),
    b(p.gift),
    String(p.rank),
  ]);

  const variantRows = [];
  const stockRows = [];
  const seenSkus = new Set();
  for (const p of PRODUCTS) {
    for (const colour of p.colours) {
      const swatch = COLOURS[colour]?.swatch;
      if (!swatch) throw new Error(`Unknown colour ${colour} on ${p.slug}`);
      for (const size of p.sizes ?? [null]) {
        const sku = ["LLI", p.slug.toUpperCase(), colour.slice(0, 3).toUpperCase(), size]
          .filter(Boolean)
          .join("-");
        if (seenSkus.has(sku)) throw new Error(`Duplicate SKU ${sku}`);
        seenSkus.add(sku);
        if (!Number.isInteger(p.price) || p.price <= 0) throw new Error(`Bad price on ${p.slug}`);
        variantRows.push([q(p.slug), q(sku), q(colour), q(swatch), q(size), String(p.price * 100)]);
        stockRows.push([q(sku), String(STOCK_QTY[p.stock])]);
      }
    }
  }

  const imageRows = PRODUCTS.flatMap((p) => {
    if (new Set(p.images).size !== p.images.length) throw new Error(`Duplicate image on ${p.slug}`);
    return p.images.map((name, pos) => [q(p.slug), q(key(name)), String(pos)]);
  });
  const productCategoryRows = PRODUCTS.map((p) => [q(p.slug), q(slugify(p.type))]);

  const collectionRows = COLLECTIONS.map((c, i) => [
    q(c.slug),
    q(c.title),
    q(c.eyebrow),
    q(c.intro),
    q(key(c.image)),
    String(i),
  ]);
  const collectionProductRows = COLLECTIONS.flatMap((c) =>
    PRODUCTS.filter(c.filter).map((p) => [q(c.slug), q(p.slug), String(p.rank)]),
  );

  return `-- DEVELOPMENT DATA ONLY. Generated by backend/scripts/generate-dev-catalogue-seed.mjs from
-- src/lib/catalog.ts. Do not edit by hand; do not run in production.
--
-- ${PRODUCTS.length} products, ${variantRows.length} variants (colour x size), ${usedImages.length} placeholder media rows,
-- ${COLLECTIONS.length} collections (membership computed with the storefront's own filters), ${childRows.length + parents.length} categories.
-- Opening stock is a placeholder (in=${STOCK_QTY.in}, low=${STOCK_QTY.low}, out=${STOCK_QTY.out} per variant). No cost prices, HSN codes or tax
-- rates: those need real data (roadmap D14, D19). Media keys point at a dev prefix; no files are uploaded.
-- Idempotent: re-running adds nothing and never resets stock.
--
-- Requires migrations 0001 and 0002 (the reference seed is not needed).
-- Guard: the session must opt in with  SET lli.allow_dev_seed = 'on';

DO $$
BEGIN
  IF coalesce(current_setting('lli.allow_dev_seed', true), 'off') <> 'on' THEN
    RAISE EXCEPTION 'dev catalogue seed refused: run  SET lli.allow_dev_seed = ''on'';  first, and only on a development database';
  END IF;
END;
$$;

-- Categories
INSERT INTO categories (slug, name, sort_order) VALUES
${rows(parents.map((p, i) => [q(p.slug), q(p.name), String(i)]))}
ON CONFLICT (slug) DO NOTHING;

INSERT INTO categories (slug, name, parent_id, sort_order)
SELECT v.slug, v.name, par.id, v.sort_order
  FROM (VALUES
${rows(childRows)}
  ) AS v (slug, name, parent_slug, sort_order)
  JOIN categories par ON par.slug = v.parent_slug
ON CONFLICT (slug) DO NOTHING;

-- Media (placeholders)
INSERT INTO media_assets (storage_key, content_type, size_bytes, sha256, alt_text, status)
SELECT v.storage_key, v.content_type, v.size_bytes, v.sha256, v.alt_text, 'READY'::media_status
  FROM (VALUES
${rows(mediaRows)}
  ) AS v (storage_key, content_type, size_bytes, sha256, alt_text)
ON CONFLICT (storage_key) DO NOTHING;

-- Products
INSERT INTO products (slug, name, tagline, product_type, gender, material, dimensions, status, is_new, is_bestseller, is_gift, rank)
SELECT v.slug, v.name, v.tagline, v.product_type, v.gender::gender, v.material, v.dimensions, 'ACTIVE'::product_status,
       v.is_new, v.is_bestseller, v.is_gift, v.rank
  FROM (VALUES
${rows(productRows)}
  ) AS v (slug, name, tagline, product_type, gender, material, dimensions, is_new, is_bestseller, is_gift, rank)
ON CONFLICT (slug) DO NOTHING;

-- Variants (prices in paise)
INSERT INTO product_variants (product_id, sku, colour_name, colour_swatch, size, price_paise)
SELECT p.id, v.sku, v.colour_name, v.colour_swatch, v.size, v.price_paise
  FROM (VALUES
${rows(variantRows)}
  ) AS v (product_slug, sku, colour_name, colour_swatch, size, price_paise)
  JOIN products p ON p.slug = v.product_slug
ON CONFLICT (sku) DO NOTHING;

-- Opening stock, with a ledger row for every non-zero quantity. Existing inventory rows are left alone.
WITH seed (sku, qty) AS (VALUES
${rows(stockRows)}
),
inserted AS (
  INSERT INTO inventory (variant_id, on_hand)
  SELECT v.id, s.qty FROM seed s JOIN product_variants v ON v.sku = s.sku
  ON CONFLICT (variant_id) DO NOTHING
  RETURNING variant_id, on_hand
)
INSERT INTO inventory_movements (variant_id, delta, reason, note)
SELECT variant_id, on_hand, 'ADJUSTMENT'::movement_reason, 'dev seed: opening stock'
  FROM inserted WHERE on_hand > 0;

-- Product images
INSERT INTO product_images (product_id, media_id, position)
SELECT p.id, m.id, v.position
  FROM (VALUES
${rows(imageRows)}
  ) AS v (product_slug, storage_key, position)
  JOIN products p ON p.slug = v.product_slug
  JOIN media_assets m ON m.storage_key = v.storage_key
ON CONFLICT (product_id, media_id) DO NOTHING;

-- Product to category
INSERT INTO product_categories (product_id, category_id)
SELECT p.id, c.id
  FROM (VALUES
${rows(productCategoryRows)}
  ) AS v (product_slug, category_slug)
  JOIN products p ON p.slug = v.product_slug
  JOIN categories c ON c.slug = v.category_slug
ON CONFLICT DO NOTHING;

-- Collections (manual membership, copied from the storefront's filters)
INSERT INTO collections (slug, title, eyebrow, intro, kind, hero_media_id, sort_order, status)
SELECT v.slug, v.title, v.eyebrow, v.intro, 'MANUAL'::collection_kind, m.id, v.sort_order, 'PUBLISHED'::publish_status
  FROM (VALUES
${rows(collectionRows)}
  ) AS v (slug, title, eyebrow, intro, hero_key, sort_order)
  JOIN media_assets m ON m.storage_key = v.hero_key
ON CONFLICT (slug) DO NOTHING;

INSERT INTO collection_products (collection_id, product_id, position)
SELECT c.id, p.id, v.position
  FROM (VALUES
${rows(collectionProductRows)}
  ) AS v (collection_slug, product_slug, position)
  JOIN collections c ON c.slug = v.collection_slug
  JOIN products p ON p.slug = v.product_slug
ON CONFLICT DO NOTHING;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = await buildDevCatalogueSql();
  writeFileSync(outFile, sql, "utf8");
  console.log(`Wrote ${outFile}`);
}
